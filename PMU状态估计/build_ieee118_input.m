function summary=build_ieee118_input(matpower_root)
%BUILD_IEEE118_INPUT Freeze the current rectangular-PMU model on IEEE118.
% Uses local MATPOWER only for the AC operating point and an independent
% admittance reference. No results from earlier SCADA/PMU experiments enter.
% Output files are written beside this function, after strict verification.
here=fileparts(mfilename('fullpath'));
generator_path=[mfilename('fullpath') '.m'];
assert(nargin==1 && isfolder(matpower_root),'PMU118:MATPOWERPath', ...
    'Supply the local MATPOWER 7.1 root directory.');
matpower_root=char(matpower_root);
oldpath=path;oldrng=rng;
cleanup=onCleanup(@()restore_settings(oldpath,oldrng)); %#ok<NASGU>
parts={'lib','data',fullfile('mptest','lib'), ...
    fullfile('mp-opt-model','lib'),fullfile('mips','lib'),fullfile('most','lib')};
for k=1:numel(parts)
    p=fullfile(matpower_root,parts{k});
    assert(isfolder(p),'PMU118:MATPOWERPath','Required directory missing: %s',p);
    addpath(p,'-begin');
end
assert(isfile(fullfile(here,'pmu_build.m')),'PMU118:PMUBuild', ...
    'Copy the current desktop pmu_build.m into this experiment directory first.');
addpath(here,'-begin');
names={'case118','runpf','makeYbus','ext2int','mpoption','pmu_build'};
expected={fullfile(matpower_root,'data','case118.m'), ...
    fullfile(matpower_root,'lib','runpf.m'), ...
    fullfile(matpower_root,'lib','makeYbus.m'), ...
    fullfile(matpower_root,'lib','ext2int.m'), ...
    fullfile(matpower_root,'lib','mpoption.m'),fullfile(here,'pmu_build.m')};
sources=struct([]);
for k=1:numel(names)
    actual=which(names{k});
    assert(strcmpi(strrep(actual,'/','\'),strrep(expected{k},'/','\')), ...
        'PMU118:ShadowedFunction','Unexpected source for %s: %s',names{k},actual);
    entry=struct('function_name',names{k},'path',actual, ...
        'sha256',file_sha256(actual));
    if k==1,sources=entry;else,sources(k)=entry;end %#ok<AGROW>
end

% Keep external and internal representations explicit. ext2int also handles
% offline equipment and bus renumbering; all c matrices use internal order.
external=case118();
mpc=ext2int(external);
assert(size(mpc.bus,1)==118 && size(mpc.branch,1)==186, ...
    'PMU118:CaseDimensions','Unexpected canonical IEEE118 dimensions.');
mpopt=mpoption('model','AC','pf.alg','NR','pf.tol',1e-10, ...
    'pf.enforce_q_lims',0,'verbose',0,'out.all',0);
[pf,success]=runpf(external,mpopt);
assert(success && pf.success,'PMU118:PowerFlow','MATPOWER AC power flow failed.');
solved=ext2int(pf);
assert(isequal(mpc.order.bus.i2e,solved.order.bus.i2e) ...
    && isequal(mpc.order.branch.status.on,solved.order.branch.status.on) ...
    && isequal(mpc.bus(:,1),solved.bus(:,1)) ...
    && isequal(mpc.branch(:,1:13),solved.branch(:,1:13)), ...
    'PMU118:PowerFlowOrder','Power flow changed the network or internal order.');
V=solved.bus(:,8).*exp(1i*pi/180*solved.bus(:,9));
assert(all(isfinite(V)) && all(abs(V)>0),'PMU118:PowerFlowState', ...
    'Power flow returned an invalid complex voltage.');

% Assemble c directly from numerical bus/branch/gen data, independently of
% makeYbus. The older desktop solve_pf is deliberately never called.
c=assemble_desktop_case(mpc,expected{1});
[Yref,Yfref,Ytref]=makeYbus(mpc.baseMVA,mpc.bus,mpc.branch);
network_check=check_network(c,V,mpc,solved,Yref,Yfref,Ytref);
assert(network_check.passed,'PMU118:NetworkVerification', ...
    'Independent IEEE118 AC network verification failed.');

sigma=1e-3;lambda=.005;
nl=numel(c.branch.f);
current_counts=[2*nl,nl,ceil(nl/2)];
base_current_counts=[40,20,10];base_bad_counts=[2,4,6];
instances=cell(45,1);scenario_summary=struct([]);instance_summary=struct([]);
caseid=0;scenario_id=0;
for j=1:numel(current_counts)
    nc=current_counts(j);base_nc=base_current_counts(j);
    expected_m=2*(c.n+nc);base_m=2*(14+base_nc);
    for base_bad=base_bad_counts
        actual_bad=round(expected_m*base_bad/base_m);
        scenario_id=scenario_id+1;
        entry=struct('Currents',nc, ...
            'BaseCurrents',base_nc,'StateDimension',2*c.n, ...
            'MeasurementDimension',expected_m,'BaseMeasurementDimension',base_m, ...
            'BaseBadData',base_bad,'BadData',actual_bad, ...
            'BaseBadDataFraction',base_bad/base_m, ...
            'BadDataFraction',actual_bad/expected_m);
        if scenario_id==1,scenario_summary=entry;else,scenario_summary(scenario_id)=entry;end %#ok<AGROW>
        for sd=1:5
            caseid=caseid+1;seed=1000*sd+base_bad;
            inst=pmu_build(c,V,1:c.n,sigma,seed,actual_bad,1:nc);
            assert(inst.m==expected_m && inst.n==118 && inst.rank==236 ...
                && size(inst.G,2)==236 && size(inst.H,1)==c.n+nc ...
                && numel(inst.current_selection)==nc ...
                && numel(inst.bad_indices)==actual_bad ...
                && nnz(inst.bad)==actual_bad, ...
                'PMU118:InstanceDimensions','Unexpected PMU model dimensions or corruption count.');
            assert(all(isfinite(inst.G(:))) && all(isfinite(inst.y(:))) ...
                && norm(inst.G*inst.true_xi-inst.ytrue,inf)<=1e-10*max(1,norm(inst.ytrue,inf)) ...
                && norm(inst.y-inst.ytrue-inst.noise-inst.bad,inf)<=1e-12, ...
                'PMU118:InstanceIdentity','PMU measurement identity failed.');
            inst=rmfield(inst,'proj');
            inst.Currents=nc;inst.BadData=actual_bad;inst.BaseBadData=base_bad;
            inst.SeedIndex=sd;inst.RandomSeed=seed;inst.CaseSystem='IEEE118';
            inst.CaseID=caseid;inst.lambda=lambda;
            inst.BaseCurrents=base_nc;inst.MeasurementDimension=expected_m;
            inst.StateDimension=2*c.n;inst.BadDataFraction=actual_bad/expected_m;
            inst.BaseBadDataFraction=base_bad/base_m;
            instances{caseid}=inst;
            entry=struct('CaseID',caseid,'CaseSystem','IEEE118', ...
                'Currents',nc,'BaseCurrents',base_nc,'BadData',actual_bad, ...
                'BaseBadData',base_bad,'SeedIndex',sd,'RandomSeed',seed, ...
                'MeasurementDimension',inst.m,'StateDimension',2*inst.n, ...
                'BadDataFraction',actual_bad/inst.m, ...
                'BaseBadDataFraction',base_bad/base_m,'Rank',inst.rank, ...
                'ConditionNumber',inst.cond);
            if caseid==1,instance_summary=entry;else,instance_summary(caseid)=entry;end %#ok<AGROW>
        end
    end
end
assert(caseid==45 && all(~cellfun(@isempty,instances)), ...
    'PMU118:InstanceCount','Expected exactly 45 frozen IEEE118 instances.');

provenance=struct('created_utc',char(datetime('now','TimeZone','UTC', ...
    'Format','yyyy-MM-dd''T''HH:mm:ss''Z''')), ...
    'case_system','IEEE118','matpower_root',matpower_root, ...
    'matpower_version',mpver(),'matlab_release',version('-release'), ...
    'generator',generator_path,'generator_sha256',file_sha256(generator_path), ...
    'sources',sources,'power_flow_algorithm','AC Newton polar', ...
    'power_flow_tolerance',mpopt.pf.tol,'enforce_generator_q_limits',false, ...
    'true_state_source','Local MATPOWER runpf(case118), preserving the reference angle', ...
    'admittance_source','Independent bus/branch/gen assembly checked against local makeYbus', ...
    'bus_external_ids',mpc.order.bus.i2e(:)', ...
    'branch_external_rows',mpc.order.branch.status.on(:)', ...
    'input_bus_count',size(external.bus,1),'input_generator_count',size(external.gen,1), ...
    'input_branch_count',size(external.branch,1), ...
    'online_generator_count',nnz(mpc.gen(:,8)>0), ...
    'online_branch_count',nnz(mpc.branch(:,11)>0), ...
    'sigma_per_real_component',sigma,'lambda',lambda, ...
    'current_selection_rule','1:Currents in existing interleaved FROM/TO branch order', ...
    'bad_data_count_rule','round(m118 * BaseBadData / (2*(14+BaseCurrents)))', ...
    'seed_rule','1000*SeedIndex + BaseBadData', ...
    'corruption_definition','Existing pmu_build: 20 to 100 sigma per selected real component', ...
    'earlier_experiment_results_used',false);
summary=struct('case_system','IEEE118','instance_count',caseid, ...
    'baseMVA',c.baseMVA,'bus_count',c.n,'branch_count',nl, ...
    'state_dimension',2*c.n,'current_counts',current_counts, ...
    'sigma',sigma,'lambda',lambda,'network_verified',network_check.passed, ...
    'scenarios',scenario_summary,'instances',instance_summary, ...
    'input_file',fullfile(here,'input_ieee118.mat'));
save(summary.input_file,'c','V','instances','network_check','provenance','summary','-v7');
write_json(fullfile(here,'input_ieee118_summary.json'),summary);
write_json(fullfile(here,'input_ieee118_network_check.json'),network_check);
write_json(fullfile(here,'input_ieee118_provenance.json'),provenance);
end

function c=assemble_desktop_case(mpc,source_path)
bus=mpc.bus;gen=mpc.gen;br=mpc.branch;
n=size(bus,1);m=size(br,1);baseMVA=mpc.baseMVA;
assert(isfinite(baseMVA) && baseMVA>0 && isequal(bus(:,1),(1:n)'), ...
    'PMU118:BusOrder','Invalid base or internal bus numbering.');
assert(all(isfinite(bus(:))) && all(isfinite(gen(:))) && all(isfinite(br(:))), ...
    'PMU118:NonfiniteData','Nonfinite MATPOWER numerical data.');
on=gen(:,8)>0;gb=gen(on,1);
assert(all(gb>=1 & gb<=n & gb==fix(gb)),'PMU118:GeneratorBus','Invalid generator buses.');
Pg=accumarray(gb,gen(on,2),[n 1]);Qg=accumarray(gb,gen(on,3),[n 1]);
[ref,pv,pq]=bustypes(bus,gen);
assert(numel(ref)==1 && numel(unique([ref;pv;pq]))==n, ...
    'PMU118:BusTypes','Expected one reference bus and a complete bus-type partition.');
types=zeros(n,1);types(pv)=2;types(ref)=3;
B=struct('id',bus(:,1),'type',types,'Vm',bus(:,8),'Va',bus(:,9), ...
    'Pg',Pg,'Qg',Qg,'Pd',bus(:,3),'Qd',bus(:,4), ...
    'Gs',bus(:,5)/baseMVA,'Bs',bus(:,6)/baseMVA, ...
    'Qmin',accumarray(gb,gen(on,5),[n 1]), ...
    'Qmax',accumarray(gb,gen(on,4),[n 1]), ...
    'external_id',mpc.order.bus.i2e(:));
E=struct('f',br(:,1),'t',br(:,2),'r',br(:,3),'x',br(:,4), ...
    'b',br(:,5),'tap',br(:,9),'shift',br(:,10),'status',br(:,11), ...
    'external_row',mpc.order.branch.status.on(:));
E.tap(E.tap==0)=1;
assert(all(E.f>=1 & E.f<=n & E.f==fix(E.f)) ...
    && all(E.t>=1 & E.t<=n & E.t==fix(E.t)) && all(E.f~=E.t) ...
    && all(E.tap>0) && all(abs(E.r+1i*E.x)>0) ...
    && all(ismember(E.status,[0 1])), ...
    'PMU118:BranchData','Invalid branch endpoints, impedance, tap or status.');
series=E.status./(E.r+1i*E.x);charging=1i*E.status.*E.b/2;
tap=E.tap.*exp(1i*pi/180*E.shift);
E.Yff=(series+charging)./abs(tap).^2;
E.Yft=-series./conj(tap);E.Ytf=-series./tap;E.Ytt=series+charging;
Cf=sparse((1:m)',E.f,ones(m,1),m,n);Ct=sparse((1:m)',E.t,ones(m,1),m,n);
Yf=spdiags(E.Yff,0,m,m)*Cf+spdiags(E.Yft,0,m,m)*Ct;
Yt=spdiags(E.Ytf,0,m,m)*Cf+spdiags(E.Ytt,0,m,m)*Ct;
Y=Cf'*Yf+Ct'*Yt+spdiags(B.Gs+1i*B.Bs,0,n,n);
c=struct('n',n,'baseMVA',baseMVA,'bus',B,'branch',E,'Y',full(Y), ...
    'Yf',Yf,'Yt',Yt,'bus_file',source_path,'branch_file',source_path, ...
    'CaseSystem','IEEE118');
end

function report=check_network(c,V,mpc,solved,Yref,Yfref,Ytref)
n=c.n;E=c.branch;B=c.bus;
matrix_errors=[norm(c.Y-Yref,inf),norm(c.Yf-Yfref,inf),norm(c.Yt-Ytref,inf)];
matrix_scale=max([1,norm(Yref,inf),norm(Yfref,inf),norm(Ytref,inf)]);
[If,It,injected]=circuit_currents(c,V);
from_error=norm(c.Yf*V-If,inf);to_error=norm(c.Yt*V-It,inf);
kcl_error=norm(c.Y*V-injected,inf);
W=(1+.03*cos((1:n)'*sqrt(2))).*exp(1i*.1*sin((1:n)'*sqrt(3)));
[Ifw,Itw,injectedw]=circuit_currents(c,W);
alternate_error=max([norm(c.Yf*W-Ifw,inf),norm(c.Yt*W-Itw,inf), ...
    norm(c.Y*W-injectedw,inf)]);
current_scale=max([1;abs(If);abs(It);abs(injected);abs(Ifw);abs(Itw);abs(injectedw)]);
S=V.*conj(c.Y*V);nonref=B.type~=3;pq=B.type==0;ref=find(B.type==3);
Psp=(B.Pg-B.Pd)/c.baseMVA;Qsp=(B.Qg-B.Qd)/c.baseMVA;
p_error=norm(real(S(nonref))-Psp(nonref),inf);
q_error=norm(imag(S(pq))-Qsp(pq),inf);
on=solved.gen(:,8)>0;gb=solved.gen(on,1);
solved_pg=accumarray(gb,solved.gen(on,2),[n 1]);
solved_qg=accumarray(gb,solved.gen(on,3),[n 1]);
solved_S=(solved_pg-B.Pd+1i*(solved_qg-B.Qd))/c.baseMVA;
all_power_error=norm(S-solved_S,inf);
controlled_gen=mpc.gen(:,8)>0 & B.type(mpc.gen(:,1))~=0;
controlled_bus=mpc.gen(controlled_gen,1);
voltage_setpoint_error=norm(abs(V(controlled_bus))-mpc.gen(controlled_gen,6),inf);
ref_angle_error=norm(angle(V(ref).*exp(-1i*pi/180*mpc.bus(ref,9))),inf);
initial_setpoint_mismatch=mpc.gen(controlled_gen,6)-mpc.bus(controlled_bus,8);
matrix_tolerance=1e-10*matrix_scale;current_tolerance=1e-10*current_scale;
power_tolerance=1e-8;state_tolerance=1e-10;
checks=[matrix_errors,from_error,to_error,kcl_error,alternate_error, ...
    p_error,q_error,all_power_error,voltage_setpoint_error,ref_angle_error];
passed=all(isfinite(checks)) && max(matrix_errors)<=matrix_tolerance ...
    && max([from_error,to_error,kcl_error,alternate_error])<=current_tolerance ...
    && max([p_error,q_error,all_power_error])<=power_tolerance ...
    && max([voltage_setpoint_error,ref_angle_error])<=state_tolerance;
report=struct('passed',passed,'canonical_reference_checked',true, ...
    'reference_Ybus_error',matrix_errors(1),'reference_Yf_error',matrix_errors(2), ...
    'reference_Yt_error',matrix_errors(3),'matrix_absolute_tolerance',matrix_tolerance, ...
    'from_terminal_current_error',from_error,'to_terminal_current_error',to_error, ...
    'kcl_error',kcl_error,'alternate_state_current_error',alternate_error, ...
    'current_absolute_tolerance',current_tolerance, ...
    'nonreference_active_power_balance_error',p_error, ...
    'pq_reactive_power_balance_error',q_error, ...
    'all_bus_solved_complex_power_balance_error',all_power_error, ...
    'power_balance_tolerance_pu',power_tolerance, ...
    'controlled_generator_voltage_setpoint_error',voltage_setpoint_error, ...
    'reference_angle_error_radians',ref_angle_error, ...
    'reference_bus_internal',ref,'reference_bus_external',B.external_id(ref), ...
    'reference_angle_degrees',angle(V(ref))*180/pi, ...
    'pv_bus_count',nnz(B.type==2),'pq_bus_count',nnz(pq), ...
    'nonzero_bus_shunt_count',nnz(B.Gs~=0 | B.Bs~=0), ...
    'nonunity_tap_count',nnz(E.tap~=1),'nonzero_shift_count',nnz(E.shift~=0), ...
    'generator_voltage_setpoint_mismatch_buses', ...
    B.external_id(controlled_bus(abs(initial_setpoint_mismatch)>1e-12))', ...
    'bus_count',n,'branch_count',numel(E.f),'baseMVA',c.baseMVA);
end

function [If,It,injected]=circuit_currents(c,V)
E=c.branch;n=c.n;tap=E.tap.*exp(1i*pi/180*E.shift);
series=E.status./(E.r+1i*E.x);charging=1i*E.status.*E.b/2;
Vp=V(E.f)./tap;Vt=V(E.t);
If=(series.*(Vp-Vt)+charging.*Vp)./conj(tap);
It=series.*(Vt-Vp)+charging.*Vt;
injected=accumarray(E.f,If,[n 1])+accumarray(E.t,It,[n 1]) ...
    +(c.bus.Gs+1i*c.bus.Bs).*V;
end

function hash=file_sha256(file)
fid=fopen(file,'rb');assert(fid>0,'PMU118:HashFile','Cannot open source: %s',file);
cleanup=onCleanup(@()fclose(fid)); %#ok<NASGU>
bytes=fread(fid,Inf,'*uint8');
md=javaMethod('getInstance','java.security.MessageDigest','SHA-256');
md.update(typecast(bytes(:),'int8'));
digest=typecast(md.digest(),'uint8');
hash=lower(reshape(dec2hex(digest,2).',1,[]));
end

function write_json(file,value)
txt=jsonencode(value,'PrettyPrint',true);
fid=fopen(file,'w','n','UTF-8');assert(fid>0,'PMU118:JSONFile','Cannot write %s',file);
cleanup=onCleanup(@()fclose(fid)); %#ok<NASGU>
fwrite(fid,unicode2native(txt,'UTF-8'),'uint8');fprintf(fid,'\n');
end

function restore_settings(oldpath,oldrng)
path(oldpath);rng(oldrng);
end
